"""Browser capabilities required by the collection use case."""

from pathlib import Path
from typing import Protocol


class CollectionAdapter(Protocol):
    @property
    def url(self) -> str: ...
    async def navigate(self, url: str) -> None: ...
    async def dismiss_known_overlays(self) -> None: ...
    async def check_login(self, platform: str) -> None: ...
    def validate_rules(self) -> None: ...
    async def new_chat(self) -> None: ...
    async def has_messages(self) -> bool: ...
    async def configure(self, requested: bool | None) -> dict: ...
    async def configure_thinking(self, requested: bool | None) -> dict: ...
    async def confirm_thinking(self, requested: bool | None) -> None: ...
    async def fill_question(self, question: str) -> None: ...
    async def send(self) -> None: ...
    async def confirm_question(self, question: str) -> None: ...
    async def current_question(self, question: str): ...
    async def wait_finished(self, question: str, timeout: int = 300) -> bool: ...
    async def collect(
        self, question: str, folder: Path, answer_complete: bool, platform: str
    ) -> dict: ...
