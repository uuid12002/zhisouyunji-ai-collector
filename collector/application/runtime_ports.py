"""Outbound contracts for browser collection, workers and the desktop UI."""

from pathlib import Path
from typing import Protocol


class ProgressReporter(Protocol):
    async def __call__(self, stage: str, checkpoint: dict | None = None) -> None: ...


class Collector(Protocol):
    async def __call__(self, job: dict, report: ProgressReporter, folder: Path) -> dict: ...


class JobGateway(Protocol):
    async def progress(self, stage: str, checkpoint: dict | None = None) -> dict: ...
    async def upload(self, item: dict, raw: bytes) -> dict: ...
    async def complete(self, answer: str, evidence: dict) -> dict: ...
    async def fail(self, code: str, message: str, waiting_human: bool) -> dict: ...


class EvidenceSpool(Protocol):
    folder: Path

    def capture(self, request_hash: str) -> dict | None: ...
    def checkpoint(self, update: dict) -> None: ...
    def restore(self, job: dict) -> dict: ...
    def save_capture(self, result: dict, request_hash: str, attempt: int) -> None: ...
    def read_artifact(self, item: dict) -> bytes: ...
    def receipt(self, value: dict) -> None: ...
    def error(self, exception: Exception) -> None: ...


class DeviceGateway(Protocol):
    async def heartbeat(self, payload: dict) -> dict: ...
    async def sync(self) -> list[dict]: ...
    async def claim(self, request_id: str) -> dict | None: ...


class DeviceState(Protocol):
    process_id: int
    run_id: str

    def stop_requested(self) -> bool: ...
    def publish(self, value: dict) -> None: ...


class DesktopRuntime(Protocol):
    def browser_sessions(self) -> dict: ...
    def planned_platforms(self) -> list[dict]: ...
    def save_planned_platforms(self, value: list[dict]) -> None: ...
    def recent_collections(self) -> list[dict]: ...
    def saved_output(self, folder: Path, item_id: str, kind: str): ...
    def load_configuration(self) -> dict: ...
    def read_connection(self, path: str) -> dict: ...
    def save_configuration(self, value: dict) -> None: ...
    def configuration_bytes(self) -> bytes | None: ...
    def restore_configuration(self, value: bytes | None) -> None: ...
    def set_startup(self, enabled: bool) -> None: ...
    def spawn(self, *args: str) -> tuple: ...
    def clear_stop(self) -> None: ...
    def stop(self) -> None: ...
    def open_home(self) -> None: ...
    def worker_status(self) -> dict: ...
    def local_status(self, folder: Path) -> dict | None: ...
    def create_local_test(self, platform: str, question: str) -> Path: ...
    def open_result(self, folder: Path) -> None: ...
    def create_local_batch(self, request: dict) -> Path: ...
    def stop_local_batch(self, folder: Path) -> None: ...
    def open_batch_item(self, folder: Path, item_id: str) -> None: ...


class LocalTestStorage(Protocol):
    request: dict
    folder: Path
    job_id: str

    def started(self) -> bool: ...
    def checkpoint(self, value: dict) -> None: ...
    def status(self, value: dict) -> None: ...
    def result(self, value: dict, html: str) -> None: ...


class LocalBatchStorage(Protocol):
    request: dict

    def started(self) -> bool: ...
    def stop_requested(self) -> bool: ...
    def prepare_item(self, item: dict) -> Path: ...
    def publish(self, state: dict, report: str | None) -> None: ...
